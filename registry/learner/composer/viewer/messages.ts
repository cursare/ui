function formatMessage(message: string, params?: Record<string, string | number>) {
  if (!params) return message
  return message.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? `{${key}}`))
}

export function editorMessage(
  messages: EditorMessages | null | undefined,
  key: string,
  params?: Record<string, string | number>,
) {
  const template = messages?.[key] ?? DEFAULT_EDITOR_MESSAGES[key] ?? key
  return formatMessage(template, params)
}
